"""Generate the committed sample report (examples/sample-report.md / .json).

This runs a small campaign through the *real* Runner against the in-memory
simulation (DryRunClient) — so the output is genuine tool output in the genuine
format, just not from a live tenant. Re-run after changing the report format:

    PYTHONPATH=src python examples/make_sample_report.py

The committed files are clearly labelled as simulated. A real-tenant run drops
the same shape into chaos.yaml's results_path, read by `troop report`.
"""

from __future__ import annotations

import os
import tempfile

from troop.client import DryRunClient
from troop.journal import Journal
from troop.models import Blast, Change, Fault, Reversibility, Target
from troop.models import Plan
from troop.report import ResultStore, result_row, summarize, to_json, to_markdown
from troop.runner import Runner
from troop.safety import Fence, Guard

CANARY = "chaos-canary"
HERE = os.path.dirname(os.path.abspath(__file__))


class Scenario(DryRunClient):
    """A sim whose detection flips on the mutation, so we get a real verdict."""

    def __init__(self, detect_before: bool, detect_after: bool):
        super().__init__(store={"OBJ": {"objectId": "OBJ", "scope": "MZ-CANARY",
                                        "schemaId": "builtin:alerting.profile",
                                        "updateToken": "t",
                                        "value": {"chaos-canary": True, "x": 1}}})
        self.b, self.a, self.mutated = detect_before, detect_after, False

    def update_object(self, object_id, value, update_token=None):
        super().update_object(object_id, value, update_token)
        self.store[object_id]["value"] = value
        self.mutated = True

    def recent_problems(self, since_ms):
        fires = self.a if self.mutated else self.b
        return [{"title": "chaos problem", "managementZones": [{"id": "MZ-CANARY"}]}] if fires else []


def _plan(monkey, oid):
    ch = Change(Target("builtin:alerting.profile", oid, "MZ-CANARY", label=CANARY),
                before={"value": {"chaos-canary": True, "x": 1}},
                after={"value": {"chaos-canary": True, "x": 2}}, note="mutate canary config")
    return Plan(monkey, f"{monkey} experiment", Reversibility.AUTO, Blast.OBJECT, [ch],
                fault="canary ERROR_EVENT", expected_signal="routed alert")


def main() -> None:
    guard = Guard(fence=Fence(allowed_scopes=frozenset({"MZ-CANARY"})), dry_run=False)
    store = ResultStore(os.path.join(tempfile.mkdtemp(), "results.jsonl"))
    campaign = [
        ("baboon", True, False),    # KILLED  — detection broke
        ("ape", True, False),       # KILLED
        ("howler", True, True),     # SURVIVED — detection held (dead/redundant)
        ("mandrill", False, False),  # INCONCLUSIVE — baseline never fired
    ]
    for i, (monkey, b, a) in enumerate(campaign):
        plan = _plan(monkey, f"OBJ-{i}")
        sim = Scenario(b, a)
        sim.store[f"OBJ-{i}"] = sim.store.pop("OBJ")
        sim.store[f"OBJ-{i}"]["objectId"] = f"OBJ-{i}"
        jp = os.path.join(tempfile.mkdtemp(), "j.jsonl")
        result = Runner(sim, guard, Journal(jp)).run(plan, fault_kind=Fault.EVENT)
        store.append(result_row(result, plan, scope="MZ-CANARY", tenant="simulated"))

    summary = summarize(store.rows())
    banner = ("<!-- GENERATED by examples/make_sample_report.py against the in-memory "
              "simulation (DryRunClient), NOT a live Dynatrace tenant. "
              "It shows the shape of a real `troop report`. -->\n\n")
    with open(os.path.join(HERE, "sample-report.md"), "w", encoding="utf-8") as fh:
        fh.write(banner + to_markdown(summary))
    with open(os.path.join(HERE, "sample-report.json"), "w", encoding="utf-8") as fh:
        fh.write(to_json({**summary, "_source": "simulated (DryRunClient), not a live tenant"}))
    print("wrote examples/sample-report.md and examples/sample-report.json")


if __name__ == "__main__":
    main()
